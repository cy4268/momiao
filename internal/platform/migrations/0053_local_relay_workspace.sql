CREATE TABLE relay.groups (
 name text PRIMARY KEY,
 description text NOT NULL DEFAULT '',
 ratio numeric NOT NULL DEFAULT 1 CHECK(ratio >= 0)
);
CREATE TABLE relay.channels (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name text NOT NULL,
 type integer NOT NULL,
 base_url text NOT NULL DEFAULT '',
 key text NOT NULL,
 models text[] NOT NULL DEFAULT '{}',
 groups text[] NOT NULL DEFAULT '{}',
 model_mapping jsonb NOT NULL DEFAULT '{}',
 priority bigint NOT NULL DEFAULT 0,
 weight bigint NOT NULL DEFAULT 0,
 enabled boolean NOT NULL DEFAULT true,
 header_override jsonb NOT NULL DEFAULT '{}',
 param_override jsonb NOT NULL DEFAULT '{}',
 channel_info jsonb NOT NULL DEFAULT '{}',
 setting jsonb NOT NULL DEFAULT '{}',
 settings jsonb NOT NULL DEFAULT '{}',
 other text NOT NULL DEFAULT '',
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE relay.logs (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id bigint NOT NULL,
 key_id bigint NOT NULL DEFAULT 0,
 key_name text NOT NULL DEFAULT '',
 model text NOT NULL DEFAULT '',
 channel_id bigint NOT NULL DEFAULT 0,
 group_name text NOT NULL DEFAULT '',
 -- Keep official log types so historical admin/login rows survive the import.
 kind smallint NOT NULL,
 prompt_tokens bigint NOT NULL DEFAULT 0,
 completion_tokens bigint NOT NULL DEFAULT 0,
 cache_read_tokens bigint NOT NULL DEFAULT 0,
 cache_write_tokens bigint NOT NULL DEFAULT 0,
 cache_write_tokens_1h bigint NOT NULL DEFAULT 0,
 cost_units bigint NOT NULL DEFAULT 0,
 duration_ms bigint NOT NULL DEFAULT 0,
 is_stream boolean NOT NULL DEFAULT false,
 status_code integer NOT NULL DEFAULT 0,
 error text NOT NULL DEFAULT '',
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX logs_created ON relay.logs(created_at);
CREATE INDEX logs_user_created ON relay.logs(user_id,created_at);
CREATE INDEX logs_user_id ON relay.logs(user_id,id DESC);
CREATE INDEX logs_model_created ON relay.logs(model,created_at);
CREATE INDEX logs_channel_created ON relay.logs(channel_id,created_at);
REVOKE ALL ON relay.groups,relay.channels,relay.logs FROM PUBLIC;
