CREATE SCHEMA relay;
CREATE TABLE relay.api_keys (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id bigint NOT NULL REFERENCES identity.users(id),
 key text NOT NULL UNIQUE,
 name text NOT NULL,
 status integer NOT NULL DEFAULT 1 CHECK(status IN (1,2,3,4)),
 purpose text NOT NULL DEFAULT 'UNCLASSIFIED' CHECK(purpose IN ('GENERAL','ROLEPLAY','UNCLASSIFIED')),
 quota_limit bigint CHECK(quota_limit >= 0),
 used_quota bigint NOT NULL DEFAULT 0 CHECK(used_quota >= 0),
 expires_at timestamptz,
 models text[],
 created_at timestamptz NOT NULL DEFAULT now(),
 accessed_at timestamptz
);
CREATE INDEX api_keys_user ON relay.api_keys(user_id,id DESC);
REVOKE ALL ON SCHEMA relay FROM PUBLIC;
REVOKE ALL ON relay.api_keys FROM PUBLIC;
